// @ts-check
import assert from 'node:assert/strict'
import { mkdtemp, mkdir, readFile, rm, writeFile } from 'node:fs/promises'
import { tmpdir } from 'node:os'
import { join } from 'node:path'
import { after, before, describe, it } from 'node:test'
import { createNoteFile, detectNote2md } from '../../../lib/host/notebook/files.js'

describe('notebook files', () => {
  /** @type {string} */
  let root
  before(async () => { root = await mkdtemp(join(tmpdir(), 'desk-one-files-')) })
  after(async () => { await rm(root, { recursive: true, force: true }) })

  it('创建空笔记：frontmatter + 标题，重名自动加序号', async () => {
    const first = await createNoteFile(root, { title: '示例笔记' })
    assert.equal(first, '示例笔记.md')
    const content = await readFile(join(root, '示例笔记.md'), 'utf8')
    assert.match(content, /^---\ndate: \d{4}-\d{2}-\d{2}\ntype: note\ntitle: 示例笔记\n/mu)
    assert.match(content, /\n# 示例笔记\n/u)
    const second = await createNoteFile(root, { title: '示例笔记' })
    assert.equal(second, '示例笔记 (2).md')
    const nested = await createNoteFile(root, { title: '分区内', folder: '分区' })
    assert.equal(nested, '分区/分区内.md')
  })

  it('note2md 工作区识别：.note2md 目录或 AGENTS 标记', async () => {
    assert.equal(await detectNote2md(root), false)
    await mkdir(join(root, '.note2md'))
    assert.equal(await detectNote2md(root), true)
    const other = await mkdtemp(join(tmpdir(), 'desk-one-md-'))
    try {
      await writeFile(join(other, 'AGENTS.md'), '<!-- Generated by note2md -->\n', 'utf8')
      assert.equal(await detectNote2md(other), true)
    } finally {
      await rm(other, { recursive: true, force: true })
    }
  })
})
