/**
 * Notebook file helpers: content hashing, note2md detection, file identity, and note creation.
 */

import { createHash } from 'node:crypto'
import { mkdir, readFile, realpath, stat, writeFile } from 'node:fs/promises'
import { dirname, join } from 'node:path'
import { NOTEBOOK_MAX_BYTES } from '../../constants.js'
import { DeskError } from '../http.js'
import type { DeskStore } from '../store.js'
import { normalizeRelativePath } from './library.js'

/** Whether one resolved absolute path stays inside the resolved library root. */
function isWithin(rootReal: string, absoluteFile: string): boolean {
  return absoluteFile === rootReal
    || absoluteFile.startsWith(`${rootReal}/`)
    || absoluteFile.startsWith(`${rootReal}\\`)
}

/**
 * Resolve one library file for identity/hash work, refusing anything that escapes the root through
 * `..` or a symbolic link. Mirrors `readPage`'s safety check so file identity cannot be assigned to
 * (or hashed from) a file outside the library.
 * @param rootPath - absolute library root.
 * @param relativePath - already normalized relative path.
 * @returns the resolved absolute file path.
 * @throws DeskError with `readPage`'s existing semantics (404 missing, 403 outside the root).
 */
async function resolveContainedFile(rootPath: string, relativePath: string): Promise<string> {
  let rootReal: string
  let fileReal: string
  try {
    rootReal = await realpath(rootPath)
    fileReal = await realpath(join(rootPath, ...relativePath.split('/')))
  } catch {
    throw new DeskError('UNKNOWN_NOTE', '文件不存在或不可访问', 404)
  }
  if (!isWithin(rootReal, fileReal)) throw new DeskError('FORBIDDEN', '文件必须位于笔记库内', 403)
  return fileReal
}

/** sha256 of one file's bytes (bounded read). */
async function fileHash(absolute: string): Promise<string> {
  const info = await stat(absolute)
  if (info.size > NOTEBOOK_MAX_BYTES) throw new DeskError('BAD_BODY', '文件过大', 400)
  const bytes = await readFile(absolute)
  return createHash('sha256').update(bytes).digest('hex')
}

/**
 * Resolve (or lazily assign) the identity of one library file.
 * @param store - unified store.
 * @param rootPath - absolute library root.
 * @param relativePath - caller-supplied relative path.
 * @returns the file identity with a fresh content hash.
 */
export async function ensureNoteFile(store: DeskStore, rootPath: string, relativePath: string) {
  const path = normalizeRelativePath(relativePath)
  const absolute = await resolveContainedFile(rootPath, path)
  const hash = await fileHash(absolute)
  return await store.ensureNoteFile({ rootPath, path, hash })
}

/** Whether the library root looks like a note2md-managed workspace. */
export async function detectNote2md(rootPath: string): Promise<boolean> {
  try {
    await stat(join(rootPath, '.note2md'))
    return true
  } catch {
    // Older workspaces only carry the generated AGENTS.md marker.
  }
  try {
    const agents = await readFile(join(rootPath, 'AGENTS.md'), 'utf8')
    return agents.includes('Generated by note2md')
  } catch {
    return false
  }
}

/**
 * Resolve the nearest existing ancestor of one write target and require it (and therefore the
 * target) to stay inside the library root. Creation must not write through a symlinked folder that
 * points outside the library; missing intermediate folders are created by the caller afterwards.
 * @param rootPath - absolute library root.
 * @param absoluteFile - absolute target path (may not exist yet).
 * @throws DeskError — 403 when the resolved ancestor escapes the root, 503 when the root itself is gone.
 */
async function assertContainedAncestor(rootPath: string, absoluteFile: string): Promise<void> {
  let rootReal: string
  try {
    rootReal = await realpath(rootPath)
  } catch {
    throw new DeskError('NOTEBOOK_UNAVAILABLE', '笔记库不可用', 503)
  }
  let candidate = dirname(absoluteFile)
  for (;;) {
    try {
      const candidateReal = await realpath(candidate)
      if (!isWithin(rootReal, candidateReal)) throw new DeskError('FORBIDDEN', '文件必须位于笔记库内', 403)
      return
    } catch (error) {
      if (error instanceof DeskError) throw error
      const parent = dirname(candidate)
      if (parent === candidate) throw new DeskError('FORBIDDEN', '文件必须位于笔记库内', 403)
      candidate = parent
    }
  }
}

/** Write a frontmatter template for one new note; returns the relative path. */
export async function createNoteFile(rootPath: string, input: {
  readonly title: string
  readonly folder?: string
}): Promise<string> {
  const title = input.title.trim()
  if (title === '') throw new DeskError('BAD_BODY', '标题不能为空')
  const folder = input.folder === undefined || input.folder.trim() === '' ? '' : normalizeRelativePath(input.folder)
  const base = title.replace(/[\\/:*?"<>|]/gu, '-').slice(0, 120)
  let relative = folder === '' ? `${base}.md` : `${folder}/${base}.md`
  for (let index = 2; index < 100; index += 1) {
    try {
      await stat(join(rootPath, ...relative.split('/')))
      relative = folder === '' ? `${base} (${index}).md` : `${folder}/${base} (${index}).md`
    } catch {
      break
    }
  }
  const absolute = join(rootPath, ...relative.split('/'))
  await assertContainedAncestor(rootPath, absolute)
  await mkdir(join(absolute, '..'), { recursive: true })
  const today = new Date().toISOString().slice(0, 10)
  const body = [
    '---',
    `date: ${today}`,
    'type: note',
    `title: ${title}`,
    'tags: []',
    '---',
    '',
    `# ${title}`,
    '',
    '',
  ].join('\n')
  await writeFile(absolute, body, 'utf8')
  return relative
}
