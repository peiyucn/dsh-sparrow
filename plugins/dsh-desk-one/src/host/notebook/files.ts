/**
 * Notebook file helpers: content hashing, note2md detection, file identity, and note creation.
 */

import { createHash } from 'node:crypto'
import { mkdir, readFile, stat, writeFile } from 'node:fs/promises'
import { join } from 'node:path'
import { NOTEBOOK_MAX_BYTES } from '../../constants.js'
import { DeskError } from '../http.js'
import type { DeskStore } from '../store.js'
import { normalizeRelativePath } from './library.js'

/** sha256 of one file's bytes (bounded read). */
async function fileHash(rootPath: string, relativePath: string): Promise<string> {
  const absolute = join(rootPath, ...relativePath.split('/'))
  const info = await stat(absolute)
  if (info.size > NOTEBOOK_MAX_BYTES) throw new DeskError('BAD_BODY', '文件过大', 400)
  const bytes = await readFile(absolute)
  return createHash('sha256').update(bytes).digest('hex')
}

/**
 * Resolve (or lazily assign) the identity of one library file.
 * @param store - unified store.
 * @param rootPath - absolute library root.
 * @param relativePath - caller-supplied relative path.
 * @returns the file identity with a fresh content hash.
 */
export async function ensureNoteFile(store: DeskStore, rootPath: string, relativePath: string) {
  const path = normalizeRelativePath(relativePath)
  const hash = await fileHash(rootPath, path)
  return await store.ensureNoteFile({ rootPath, path, hash })
}

/** Whether the library root looks like a note2md-managed workspace. */
export async function detectNote2md(rootPath: string): Promise<boolean> {
  try {
    await stat(join(rootPath, '.note2md'))
    return true
  } catch {
    // Older workspaces only carry the generated AGENTS.md marker.
  }
  try {
    const agents = await readFile(join(rootPath, 'AGENTS.md'), 'utf8')
    return agents.includes('Generated by note2md')
  } catch {
    return false
  }
}

/** Write a frontmatter template for one new note; returns the relative path. */
export async function createNoteFile(rootPath: string, input: {
  readonly title: string
  readonly folder?: string
}): Promise<string> {
  const title = input.title.trim()
  if (title === '') throw new DeskError('BAD_BODY', '标题不能为空')
  const folder = input.folder === undefined || input.folder.trim() === '' ? '' : normalizeRelativePath(input.folder)
  const base = title.replace(/[\\/:*?"<>|]/gu, '-').slice(0, 120)
  let relative = folder === '' ? `${base}.md` : `${folder}/${base}.md`
  for (let index = 2; index < 100; index += 1) {
    try {
      await stat(join(rootPath, ...relative.split('/')))
      relative = folder === '' ? `${base} (${index}).md` : `${folder}/${base} (${index}).md`
    } catch {
      break
    }
  }
  const absolute = join(rootPath, ...relative.split('/'))
  await mkdir(join(absolute, '..'), { recursive: true })
  const today = new Date().toISOString().slice(0, 10)
  const body = [
    '---',
    `date: ${today}`,
    'type: note',
    `title: ${title}`,
    'tags: []',
    '---',
    '',
    `# ${title}`,
    '',
    '',
  ].join('\n')
  await writeFile(absolute, body, 'utf8')
  return relative
}
